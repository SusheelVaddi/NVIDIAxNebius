"""Data models for AI-driven incident diagnosis.

Provides the schema for structured diagnostic outputs generated by
AI models (e.g., NVIDIA Nemotron) and validates recommended actions
against supported recovery action types.
"""

from __future__ import annotations

from typing import List, Set

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.models import RecoveryActionType

SUPPORTED_ACTION_IDS: Set[str] = {action.value for action in RecoveryActionType}


class DiagnosisResult(BaseModel):
    """Structured result of an AI diagnosis for an IT incident.

    Attributes:
        likely_cause: Root-cause hypothesis identified by the AI.
        evidence: Concrete observations and signals supporting the diagnosis.
        confidence: Assessment confidence score ranging from 0.0 to 1.0.
        recommended_action_id: Identifier of the recovery action recommended,
            validated against supported RecoveryActionType values.
        rationale: Justification for why the recommended action resolves the incident.
        uncertainty_or_notes: Caveats, alternative hypotheses, or human-operator notes.
    """

    model_config = ConfigDict(extra="forbid")

    likely_cause: str = Field(
        ...,
        description="Root-cause hypothesis identified by the diagnosis engine.",
    )
    evidence: List[str] = Field(
        ...,
        description="List of observations or signals supporting the diagnosis.",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score between 0.0 and 1.0 inclusive.",
    )
    recommended_action_id: str = Field(
        ...,
        description="Recovery action ID, must match a supported RecoveryActionType.",
    )
    rationale: str = Field(
        ...,
        description="Explanation of why this action is recommended.",
    )
    uncertainty_or_notes: str = Field(
        ...,
        description="Known uncertainties, caveats, or additional notes.",
    )

    @field_validator("recommended_action_id")
    @classmethod
    def validate_action_id(cls, v: str) -> str:
        action_val = v.value if hasattr(v, "value") else str(v)
        if action_val not in SUPPORTED_ACTION_IDS:
            allowed = ", ".join(sorted(SUPPORTED_ACTION_IDS))
            raise ValueError(
                f"Unsupported action ID '{v}'. Must be one of: {allowed}"
            )
        return action_val
